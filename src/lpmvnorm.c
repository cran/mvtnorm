/* lognormdiff (log scale, AI) */

/*
    log(Phi(b - m) - Phi(a - m)) = le + log(1 - exp(ld - le))

    where ld <= le are the log-probabilities of the two limits in the lower
    tail (lt = 1) or, for a >= m, by reflection Phi(b) - Phi(a) =
    Phi(-a) - Phi(-b), in the upper tail (lt = 0). The same idea is
    implemented by .lognormdiff() for lpRR().
*/

static double C_lognormdiff (double a, double b, double m, int *lt, double *le) {

    double ld;

    *lt = (a < m);
    ld  = pnorm((*lt ? a : b), m, 1.0, *lt, 1L);
    *le = pnorm((*lt ? b : a), m, 1.0, *lt, 1L);
    if (*le == R_NegInf) return(R_NegInf);
    /* pexp(x, log) = log(1 - exp(-x)) for x > 0 and -Inf otherwise */
    return(*le + pexp(*le - ld, 1.0, 1L, 1L));
}

/* R lpmvnorm (log scale, AI) */

SEXP R_lpmvnorm(SEXP a, SEXP b, SEXP C, SEXP center, SEXP N, SEXP J,
                SEXP W, SEXP M, SEXP tol, SEXP logLik, SEXP fast) {

    /* R slpmvnorm variables (log scale, AI) */
    
    SEXP ans;
    double *da, *db, *dC, *dW, *dans;
    double *dcenter;
    double le0, lemd0, lmax;
    int lt0;
    

    double lM, x0, intsum;
    int p, len;

    Rboolean RlogLik = asLogical(logLik);

    /* dimensions */
    
    int iM = INTEGER(M)[0]; 
    int iN = INTEGER(N)[0]; 
    int iJ = INTEGER(J)[0]; 

    da = REAL(a);
    db = REAL(b);
    dC = REAL(C);
    dW = REAL(C); // make -Wmaybe-uninitialized happy

    if (LENGTH(C) == iJ * (iJ - 1) / 2)
        p = 0;
    else 
        p = LENGTH(C) / iN;
    
    /* W length */
    
    int pW = 0;
    if (W != R_NilValue) {
        if (LENGTH(W) == (iJ - 1) * iM) {
            pW = 0;
        } else {
            if (LENGTH(W) != (iJ - 1) * iN * iM)
                error("Length of W incorrect");
            pW = 1;
        }
        dW = REAL(W);
    }
    
    /* init center */
    
    dcenter = REAL(center);
    if (LENGTH(center)) {
        if (LENGTH(center) != iN * iJ)
            error("incorrect dimensions of center");
    }
    

    int start, j, k, lt;
    double tmp, Wtmp, le, lf, lemd, x, y[(iJ > 1 ? iJ - 1 : 1)];

    /* setup return object */
    
    len = (RlogLik ? 1 : iN);
    PROTECT(ans = allocVector(REALSXP, len));
    dans = REAL(ans);
    for (int i = 0; i < len; i++)
        dans[i] = 0.0;
    

    /* univariate problem (log scale, AI) */
    
    if (iJ == 1) iM = 1;    /* one draw with an empty inner loop */
    lM = log((double) iM);
    

    if (W == R_NilValue)
        GetRNGstate();

    for (int i = 0; i < iN; i++) {

        intsum = 0.0;
        /* initialisation (log scale, AI) */
        
        x0 = 0.0;
        if (LENGTH(center))
            x0 = -dcenter[0];
        lemd0 = C_lognormdiff(da[0], db[0], x0, &lt0, &le0);
        lmax = R_NegInf;
        

        if (W != R_NilValue && pW == 0)
            dW = REAL(W);

        for (int m = 0; m < iM; m++) {

            /* init logLik loop (log scale, AI) */
            
            lt = lt0;
            le = le0;
            lemd = lemd0;
            lf = lemd0;
            start = 0;
            
            /* inner logLik loop (log scale, AI) */
            
            /* stop early when f = 0 */
            for (j = 1; j < iJ && lf > R_NegInf; j++) {

                /* compute y (log scale, AI) */
                
                Wtmp = (W == R_NilValue ? unif_rand() : dW[j - 1]);
                /* y must be finite */
                Wtmp = fmin2(fmax2(Wtmp, DBL_EPSILON), 1.0 - DBL_EPSILON);
                /* d + w (e - d) = e - (1 - w) (e - d);
                   reflection replaces w by 1 - w */
                tmp = le + log1p(-(lt ? 1.0 - Wtmp : Wtmp) * exp(lemd - le));
                y[j - 1] = qnorm(tmp, 0.0, 1.0, lt, 1L);
                
                /* compute x */
                
                x = 0.0;
                if (LENGTH(center)) {
                    for (k = 0; k < j; k++)
                        x += dC[start + k] * (y[k] - dcenter[k]);
                    x -= dcenter[j]; 
                } else {
                    for (k = 0; k < j; k++)
                        x += dC[start + k] * y[k];
                }
                
                /* update d, e (log scale, AI) */
                
                lemd = C_lognormdiff(da[j], db[j], x, &lt, &le);
                
                /* update f (log scale, AI) */
                
                start += j;
                lf += lemd;
                

            }
            
            /* increment (log scale, AI) */
            
            /* intsum = sum_m exp(lf_m - lmax), lmax = max_m lf_m */
            if (lf > lmax) {
                intsum *= exp(lmax - lf);
                lmax = lf;
            }
            if (lf != R_NegInf)
                intsum += exp(lf - lmax);
            

            if (W != R_NilValue)
                dW += iJ - 1;
        }

        /* output (log scale, AI) */
        
        dans[0] += lmax + log(intsum) - lM;
        if (!RlogLik)
            dans += 1L;
        
        /* move on */
        
        da += iJ;
        db += iJ;
        dC += p;
        if (LENGTH(center)) dcenter += iJ;
        

    }

    if (W == R_NilValue)
        PutRNGstate();

    UNPROTECT(1);
    return(ans);
}

/* R slpmvnorm (log scale, AI) */

SEXP R_slpmvnorm(SEXP a, SEXP b, SEXP C, SEXP center, SEXP N, SEXP J, SEXP W,
                 SEXP M, SEXP tol, SEXP fast) {

    /* R slpmvnorm variables (log scale, AI) */
    
    SEXP ans;
    double *da, *db, *dC, *dW, *dans;
    double *dcenter;
    double le0, lemd0, lmax;
    int lt0;
    

    double lM;
    int p, idx, idxJ1;
    /* dimensions */
    
    int iM = INTEGER(M)[0]; 
    int iN = INTEGER(N)[0]; 
    int iJ = INTEGER(J)[0]; 

    da = REAL(a);
    db = REAL(b);
    dC = REAL(C);
    dW = REAL(C); // make -Wmaybe-uninitialized happy

    if (LENGTH(C) == iJ * (iJ - 1) / 2)
        p = 0;
    else 
        p = LENGTH(C) / iN;
    
    /* W length */
    
    int pW = 0;
    if (W != R_NilValue) {
        if (LENGTH(W) == (iJ - 1) * iM) {
            pW = 0;
        } else {
            if (LENGTH(W) != (iJ - 1) * iN * iM)
                error("Length of W incorrect");
            pW = 1;
        }
        dW = REAL(W);
    }
    
    /* init center */
    
    dcenter = REAL(center);
    if (LENGTH(center)) {
        if (LENGTH(center) != iN * iJ)
            error("incorrect dimensions of center");
    }
    

    int start, j, k, lt;
    double tmp, le, lf, f, lemd, x, x0, y[(iJ > 1 ? iJ - 1 : 1)];

    /* score output object */
    
    int Jp = iJ * (iJ + 1) / 2;
    /* chol scores */

    double dp_c[Jp], ep_c[Jp], fp_c[Jp], yp_c[(iJ > 1 ? iJ - 1 : 1) * Jp];
    
    /* mean scores */

    double dp_m[Jp], ep_m[Jp], fp_m[Jp], yp_m[(iJ > 1 ? iJ - 1 : 1) * Jp];
    
    /* lower scores */

    double dp_l[Jp], ep_l[Jp], fp_l[Jp], yp_l[(iJ > 1 ? iJ - 1 : 1) * Jp];
    
    /* upper scores */

    double dp_u[Jp], ep_u[Jp], fp_u[Jp], yp_u[(iJ > 1 ? iJ - 1 : 1) * Jp];
    
    double dtmp, ndtmp, etmp, netmp, Wtmp, ytmp, xx;

    PROTECT(ans = allocMatrix(REALSXP, Jp + 1 + 3 * iJ, iN));
    dans = REAL(ans);
    for (j = 0; j < LENGTH(ans); j++) dans[j] = 0.0;
    

    /* univariate problem (log scale, AI) */
    
    if (iJ == 1) iM = 1;    /* one draw with an empty inner loop */
    lM = log((double) iM);
    

    if (W == R_NilValue)
        GetRNGstate();

    for (int i = 0; i < iN; i++) {

        /* initialisation (log scale, AI) */
        
        x0 = 0.0;
        if (LENGTH(center))
            x0 = -dcenter[0];
        lemd0 = C_lognormdiff(da[0], db[0], x0, &lt0, &le0);
        lmax = R_NegInf;
        

        if (W != R_NilValue && pW == 0)
            dW = REAL(W);

        for (int m = 0; m < iM; m++) {
            /* init score loop (log scale, AI) */
            
            /* init logLik loop (log scale, AI) */

            lt = lt0;
            le = le0;
            lemd = lemd0;
            lf = lemd0;
            start = 0;
            
            /* score c11 (log scale, AI) */

            /* dp, ep, and fp are derivatives of d, e, and f divided by
               e - d, e - d, and f, respectively: fp is the score of log(f) */
            dtmp = exp(dnorm(da[0], x0, 1.0, 1L) - lemd);
            etmp = exp(dnorm(db[0], x0, 1.0, 1L) - lemd);
            if (LENGTH(center)) {
                dp_c[0] = (R_FINITE(da[0]) ? dtmp * (da[0] - x0 - dcenter[0]) : 0);
                ep_c[0] = (R_FINITE(db[0]) ? etmp * (db[0] - x0 - dcenter[0]) : 0);
            } else {
                dp_c[0] = (R_FINITE(da[0]) ? dtmp * (da[0] - x0) : 0);
                ep_c[0] = (R_FINITE(db[0]) ? etmp * (db[0] - x0) : 0);
            }
            fp_c[0] = ep_c[0] - dp_c[0];
            
            /* score a, b (log scale, AI) */

            dp_m[0] = (R_FINITE(da[0]) ? dtmp : 0);
            ep_m[0] = (R_FINITE(db[0]) ? etmp : 0);
            dp_l[0] = dp_m[0];
            ep_u[0] = ep_m[0];
            dp_u[0] = 0;
            ep_l[0] = 0;
            fp_m[0] = ep_m[0] - dp_m[0];
            fp_l[0] = -dp_m[0];
            fp_u[0] = ep_m[0];
            
            
            /* inner score loop (log scale, AI) */
            
            /* stop early when f = 0 */
            for (j = 1; j < iJ && lf > R_NegInf; j++) {

                /* compute y (log scale, AI) */
                
                Wtmp = (W == R_NilValue ? unif_rand() : dW[j - 1]);
                /* y must be finite */
                Wtmp = fmin2(fmax2(Wtmp, DBL_EPSILON), 1.0 - DBL_EPSILON);
                /* d + w (e - d) = e - (1 - w) (e - d);
                   reflection replaces w by 1 - w */
                tmp = le + log1p(-(lt ? 1.0 - Wtmp : Wtmp) * exp(lemd - le));
                y[j - 1] = qnorm(tmp, 0.0, 1.0, lt, 1L);
                
                /* update yp for chol (log scale, AI) */
                
                /* needs e - d from j - 1, so moved before "update d, e" */
                /* = (e - d) / dnorm(y[j - 1], 0.0, 1.0, 0L) */
                ytmp = exp(lemd - dnorm(y[j - 1], 0.0, 1.0, 1L));

                for (k = 0; k < Jp; k++) yp_c[k * (iJ - 1) + (j - 1)] = 0.0;

                for (idx = 0; idx < (j + 1) * j / 2; idx++) {
                    yp_c[idx * (iJ - 1) + (j - 1)] = ytmp;
                    yp_c[idx * (iJ - 1) + (j - 1)] *= (dp_c[idx] + Wtmp * (ep_c[idx] - dp_c[idx]));
                }
                
                /* update yp for means, lower and upper */
                
                for (k = 0; k < iJ; k++)
                    yp_m[k * (iJ - 1) + (j - 1)] = 0.0;

                for (idx = 0; idx < j; idx++) {
                    yp_m[idx * (iJ - 1) + (j - 1)] = ytmp;
                    yp_m[idx * (iJ - 1) + (j - 1)] *= (dp_m[idx] + Wtmp * (ep_m[idx] - dp_m[idx]));
                }
                for (k = 0; k < iJ; k++)
                    yp_l[k * (iJ - 1) + (j - 1)] = 0.0;

                for (idx = 0; idx < j; idx++) {
                    yp_l[idx * (iJ - 1) + (j - 1)] = ytmp;
                    yp_l[idx * (iJ - 1) + (j - 1)] *= (dp_l[idx] + Wtmp * (dp_u[idx] - dp_l[idx]));
                }
                for (k = 0; k < iJ; k++)
                    yp_u[k * (iJ - 1) + (j - 1)] = 0.0;

                for (idx = 0; idx < j; idx++) {
                    yp_u[idx * (iJ - 1) + (j - 1)] = ytmp;
                    yp_u[idx * (iJ - 1) + (j - 1)] *= (ep_l[idx] + Wtmp * (ep_u[idx] - ep_l[idx]));
                }
                
                /* compute x */
                
                x = 0.0;
                if (LENGTH(center)) {
                    for (k = 0; k < j; k++)
                        x += dC[start + k] * (y[k] - dcenter[k]);
                    x -= dcenter[j]; 
                } else {
                    for (k = 0; k < j; k++)
                        x += dC[start + k] * y[k];
                }
                
                /* update d, e (log scale, AI) */
                
                lemd = C_lognormdiff(da[j], db[j], x, &lt, &le);
                
                /* score wrt new chol off-diagonals (log scale, AI) */
                
                dtmp = exp(dnorm(da[j], x, 1.0, 1L) - lemd);
                ndtmp = dtmp * (-1.0);
                etmp = exp(dnorm(db[j], x, 1.0, 1L) - lemd);
                netmp = etmp * (-1.0);

                for (k = 0; k < j; k++) {
                    idx = start + j + k;
                    if (LENGTH(center)) {
                        dp_c[idx] = ndtmp * (y[k] - dcenter[k]);
                        ep_c[idx] = netmp * (y[k] - dcenter[k]);
                    } else {
                        dp_c[idx] = ndtmp * y[k];
                        ep_c[idx] = netmp * y[k];
                    }
                    fp_c[idx] = ep_c[idx] - dp_c[idx];
                }
                
                /* score wrt new chol diagonal (log scale, AI) */
                
                idx = (j + 1) * (j + 2) / 2 - 1;
                if (LENGTH(center)) {
                    dp_c[idx] = (R_FINITE(da[j]) ? dtmp * (da[j] - x - dcenter[j]) : 0);
                    ep_c[idx] = (R_FINITE(db[j]) ? etmp * (db[j] - x - dcenter[j]) : 0);
                } else {
                    dp_c[idx] = (R_FINITE(da[j]) ? dtmp * (da[j] - x) : 0);
                    ep_c[idx] = (R_FINITE(db[j]) ? etmp * (db[j] - x) : 0);
                }
                fp_c[idx] = ep_c[idx] - dp_c[idx];
                
                /* new score means, lower and upper (log scale, AI) */
                
                dp_m[j] = (R_FINITE(da[j]) ? dtmp : 0);
                ep_m[j] = (R_FINITE(db[j]) ? etmp : 0);
                dp_l[j] = dp_m[j];
                ep_u[j] = ep_m[j];
                dp_u[j] = 0;
                ep_l[j] = 0;
                fp_l[j] = - dp_m[j];
                fp_u[j] = ep_m[j];
                fp_m[j] = fp_u[j] + fp_l[j];
                
                /* update score for chol (log scale, AI) */
                
                for (idx = 0; idx < j * (j + 1) / 2; idx++) {
                    idxJ1 = idx * (iJ - 1);
                    xx = 0.0;
                    for (k = 0; k < j; k++)
                        xx += dC[start + k] * yp_c[idxJ1 + k];

                    dp_c[idx] = ndtmp * xx;
                    ep_c[idx] = netmp * xx;
                    fp_c[idx] += ep_c[idx] - dp_c[idx];
                }
                
                /* update score means, lower and upper (log scale, AI) */
                
                for (idx = 0; idx < j; idx++) {
                    idxJ1 = idx * (iJ - 1);
                    xx = 0.0;
                    for (k = 0; k < j; k++)
                        xx += dC[start + k] * yp_m[idxJ1 + k];

                    dp_m[idx] = ndtmp * xx;
                    ep_m[idx] = netmp * xx;
                    fp_m[idx] += ep_m[idx] - dp_m[idx];

                    xx = 0.0;
                    for (k = 0; k < j; k++)
                        xx += dC[start + k] * yp_l[idxJ1 + k];

                    dp_l[idx] = ndtmp * xx;
                    dp_u[idx] = netmp * xx;
                    fp_l[idx] += dp_u[idx] - dp_l[idx];

                    xx = 0.0;
                    for (k = 0; k < j; k++)
                        xx += dC[start + k] * yp_u[idxJ1 + k];

                    ep_l[idx] = ndtmp * xx;
                    ep_u[idx] = netmp * xx;
                    fp_u[idx] += ep_u[idx] - ep_l[idx];
                }
                
                /* update f (log scale, AI) */
                
                start += j;
                lf += lemd;
                

            }
            
            /* score output (log scale, AI) */
            
            /* dans = sum_m exp(lf_m - lmax) * (1, fp_m), lmax = max_m lf_m */
            if (lf > lmax) {
                tmp = exp(lmax - lf);
                for (j = 0; j < Jp + 1 + 3 * iJ; j++)
                    dans[j] *= tmp;
                lmax = lf;
            }
            if (lf != R_NegInf) {
                f = exp(lf - lmax);
                dans[0] += f;
                for (j = 0; j < Jp; j++)
                    dans[j + 1] += f * fp_c[j];
                for (j = 0; j < iJ; j++) {
                    idx = Jp + j + 1;
                    dans[idx] += f * fp_m[j];
                    dans[idx + iJ] += f * fp_l[j];
                    dans[idx + 2 * iJ] += f * fp_u[j];
                }
            }
            

            if (W != R_NilValue)
                dW += iJ - 1;
        }

        /* normalise scores (log scale, AI) */
        
        /* scores of log(intsum), zero if intsum = 0; and log(intsum / M) */
        if (dans[0] > 0) {
            for (j = 1; j < Jp + 1 + 3 * iJ; j++)
                dans[j] /= dans[0];
        }
        dans[0] = lmax + log(dans[0]) - lM;
        
        /* move on */
        
        da += iJ;
        db += iJ;
        dC += p;
        if (LENGTH(center)) dcenter += iJ;
        

        dans += Jp + 1 + 3 * iJ;
    }

    if (W == R_NilValue)
        PutRNGstate();

    UNPROTECT(1);
    return(ans);
}

